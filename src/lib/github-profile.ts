/**
 * The GitHub profile README (github.com/<username>/<username>), built from site.yaml → github, so the README and its
 * preview on the site (/<lang>/docs/github-preview/) can never drift apart. Its images come from the site:
 * /github-banner-*.svg and /github/*.svg (pages/github/).
 *
 *   readmeHtml({ src: 'assets/' })               the README itself, served at /github/README.md: images switch
 *                                                light/dark with the viewer's GitHub theme
 *   readmeHtml({ src: '/github/', theme: 'dark' })  one theme only, with the site's own image addresses (the preview)
 */
import { site } from './config';

export type Theme = 'light' | 'dark';
/** A card's repo: "name" (yours) or "owner/name" (anyone's). The card's file is named after the repo's name. */
export const repoPath = (repo: string) => (repo.includes('/') ? repo : `${site.github.username}/${repo}`);
export const cardName = (repo: string) => repoPath(repo).split('/')[1];
export const linkSlug = (label: string) => label.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function readmeHtml({ src, banner = src, theme }: { src: string; banner?: string; theme?: Theme }) {
  const gh = site.github;
  // One image: a <picture> that follows the viewer's theme, or (for the preview) just the one theme's file.
  const img = (base: string, file: string, alt: string, width?: string) => {
    const w = width ? ` width="${width}"` : '';
    return theme
      ? `<img alt="${esc(alt)}" src="${base}${file}-${theme}.svg"${w}>`
      : `<picture><source media="(prefers-color-scheme: dark)" srcset="${base}${file}-dark.svg"><img alt="${esc(alt)}" src="${base}${file}-light.svg"${w}></picture>`;
  };
  const tagline = [site.name, gh.intro].filter(Boolean).join('. ');
  // Everything after the banner sits in one <div> with no blank lines: blank lines make GitHub's Markdown split the
  // <picture> tags apart, which breaks the light/dark switch and the two-per-row layout.
  return [
    `<a href="${site.url}">${img(banner, 'banner', tagline, '100%')}</a>`,
    '',
    '<div>',
    ...gh.links.map((l) => `<a href="${esc(l.url)}">${img(src, `link-${linkSlug(l.label)}`, l.label)}</a>`),
    ...(gh.intro || gh.heading ? ['<br><br>', img(src, 'intro', [gh.intro, gh.heading].filter(Boolean).join(' '), '100%'), '<br><br>'] : []),
    ...gh.cards.map((c) => `<a href="https://github.com/${repoPath(c.repo)}">${img(src, cardName(c.repo), `${c.title ?? cardName(c.repo)}${c.description ? `: ${c.description}` : ''}`, '49%')}</a>`),
    '</div>',
    '',
    '<!-- Generated by the website (personal-site: src/lib/github-profile.ts, from github: in src/config/site.yaml).',
    '     To update: build the site, copy dist/github/README.md here, and copy dist/github-banner-*.svg and',
    '     dist/github/*.svg into assets/ (renaming github-banner-<theme>.svg to banner-<theme>.svg). -->',
    '',
  ].join('\n');
}
